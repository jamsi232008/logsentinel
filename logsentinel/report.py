import csv, json, os
from html import escape

SEV_COLOR = {"LOW": "#3b82f6", "MEDIUM": "#f59e0b", "HIGH": "#ef4444", "CRITICAL": "#7f1d1d"}


def write_reports(incidents, stats, outdir):
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "report.json"), "w") as f:
        json.dump({"stats": stats, "incidents": incidents}, f, indent=2)
    with open(os.path.join(outdir, "iocs.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["ip", "severity", "score", "techniques", "first_seen", "last_seen"])
        for i in incidents:
            w.writerow([i["ip"], i["severity"], i["score"], ";".join(i["techniques"]), i["first_seen"], i["last_seen"]])
    with open(os.path.join(outdir, "blocklist.txt"), "w") as f:
        f.write("# Review before applying - generated by LogSentinel\n")
        for i in incidents:
            if i["severity"] in ("HIGH", "CRITICAL"):
                f.write(i["ip"] + "\n")
    with open(os.path.join(outdir, "report.html"), "w") as f:
        f.write(_html(incidents, stats))


def _badge(s):
    return f'<span class="b" style="background:{SEV_COLOR[s]}">{escape(s)}</span>'


def _html(incidents, stats):
    sev = {k: sum(1 for i in incidents if i["severity"] == k) for k in SEV_COLOR}
    mx = max(sev.values()) or 1
    bars = "".join(f'<div class="row"><span class="l">{k}</span><div class="bar" style="width:{v / mx * 100:.0f}%;background:{SEV_COLOR[k]}"></div><span>{v}</span></div>' for k, v in sev.items())
    rows = ""
    for i in incidents:
        alerts = "".join(f"<li>{_badge(a['severity'])} <b>{escape(a['rule'])}</b> ({escape(a['mitre'])}) - {escape(a['description'])}</li>" for a in i["alerts"])
        resp = "".join(f"<li>{escape(r)}</li>" for r in i["response"])
        rows += (f"<tr><td><b>{escape(i['ip'])}</b><br>{_badge(i['severity'])}</td><td>{i['score']}</td>"
                 f"<td>{escape(' > '.join(i['stages']))}{' (multi-stage)' if i['multi_stage'] else ''}</td>"
                 f"<td><ul>{alerts}</ul></td><td><ul>{resp}</ul></td></tr>")
    cards = "".join(f'<div class="card"><div class="n">{v}</div>{escape(k)}</div>' for k, v in stats.items())
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>LogSentinel Report</title>
<style>body{{font-family:system-ui,sans-serif;margin:24px;background:#0f172a;color:#e2e8f0}}
.card{{display:inline-block;background:#1e293b;padding:14px 22px;margin:0 10px 10px 0;border-radius:8px}}.n{{font-size:28px;font-weight:700}}
table{{border-collapse:collapse;width:100%;background:#1e293b}}td,th{{border:1px solid #334155;padding:8px;vertical-align:top;text-align:left;font-size:13px}}
.b{{color:#fff;padding:2px 8px;border-radius:10px;font-size:11px}}.row{{display:flex;align-items:center;gap:8px;margin:4px 0}}.l{{width:80px}}.bar{{height:14px;border-radius:3px}}ul{{margin:0;padding-left:16px}}</style></head>
<body><h1>LogSentinel - Incident Report</h1>{cards}<h2>Incidents by severity</h2>{bars}
<h2>Incidents</h2><table><tr><th>Source</th><th>Score</th><th>Kill-chain stages</th><th>Detections</th><th>Recommended response</th></tr>{rows}</table></body></html>"""
